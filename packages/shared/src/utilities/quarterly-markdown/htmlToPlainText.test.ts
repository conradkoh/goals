import { describe, expect, it } from 'vitest';

import { htmlToPlainText } from './htmlToPlainText';

describe('htmlToPlainText', () => {
  it.each<[string, string, string]>([
    ['empty string', '', ''],
    ['whitespace-only paragraph', '<p>  </p>', ''],
    ['empty tags collapse', '<p></p>', ''],
    ['single paragraph', '<p>hello</p>', 'hello'],
    ['two paragraphs concatenate without a separator', '<p>a</p><p>b</p>', 'ab'],
    ['unclosed paragraph', '<p>hello', 'hello'],
    ['br does not add a separator', 'a<br>b', 'ab'],
    ['self-closing br', 'a<br/>b', 'ab'],
    ['self-closing br with space', 'a<br />b', 'ab'],
    ['newline inside a block becomes a space', '<p>a\nb</p>', 'a b'],
    ['newlines between blocks become a space', '<p>a</p>\n<p>b</p>', 'a b'],
    ['leading and trailing whitespace is trimmed', '  <p> a </p>  ', 'a'],
    ['list items concatenate', '<ul><li>First</li><li>Second</li></ul>', 'FirstSecond'],
    ['nested inline markup keeps text', '<p>a <b>bold</b> <i>it</i></p>', 'a bold it'],
    ['quoted > inside a double-quoted attribute', '<a href="x>y">t</a>', 't'],
    ['quoted > inside a single-quoted attribute', "<a data-x='1>2'>t</a>", 't'],
    ['script element and its content are dropped', 'x<script>IN</script>y', 'xy'],
    ['unterminated script drops to end of input', 'a<script>b', 'a'],
    ['mixed-case script tags are dropped', '<SCRIPT>x</SCRIPT>y', 'y'],
    ['style element and its content are dropped', 'x<style>IN</style>y', 'xy'],
    ['iframe element and its content are dropped', 'x<iframe>IN</iframe>y', 'xy'],
    ['noscript element and its content are dropped', 'x<noscript>IN</noscript>y', 'xy'],
    ['template element and its content are dropped', 'x<template>IN</template>y', 'xy'],
    ['title element and its content are dropped', 'x<title>IN</title>y', 'xy'],
    ['xmp element and its content are dropped', 'x<xmp>IN</xmp>y', 'xy'],
    ['noembed element and its content are dropped', 'x<noembed>IN</noembed>y', 'xy'],
    ['noframes element and its content are dropped', 'x<noframes>IN</noframes>y', 'xy'],
    ['audio element and its content are dropped', 'x<audio>IN</audio>y', 'xy'],
    ['video element and its content are dropped', 'x<video>IN</video>y', 'xy'],
    ['desc element and its content are dropped', 'x<desc>IN</desc>y', 'xy'],
    [
      'foreignobject element and its content are dropped',
      'x<foreignobject>IN</foreignobject>y',
      'xy',
    ],
    ['plaintext drops itself and everything after it', 'a<plaintext>IN<b>deep</b>', 'a'],
    ['object keeps its inner text', 'x<object>IN<b>deep</b></object>y', 'xINdeepy'],
    ['textarea keeps its inner text', 'x<textarea>IN</textarea>y', 'xINy'],
    ['embed keeps its inner text', 'x<embed>IN</embed>y', 'xINy'],
    ['svg text is kept', 'x<svg><b>deep</b></svg>y', 'xdeepy'],
    ['html comment is removed', 'a<!-- c -->b', 'ab'],
    ['processing instruction is removed', 'x<?php y ?>z', 'xz'],
    ['doctype is removed', 'x<!DOCTYPE html>y', 'xy'],
    [
      'task list markup renders its text',
      '<ul data-type="taskList"><li data-checked="true"><label><input type="checkbox"><span></span></label><div><p>done</p></div></li></ul>',
      'done',
    ],
    ['entities decode exactly one pass', 'a&amp;lt;b', 'a&lt;b'],
    ['named entities decode', 'a &lt;b&gt; c', 'a <b> c'],
    ['bare comparison characters are untouched', '1 < 2 > 0', '1 < 2 > 0'],
    ['entity table decodes', '&copy; &hellip; &#x41;&#65;', '© … AA'],
    ['unknown named entity stays literal', '&bogus;', '&bogus;'],
    ['nul code point becomes the replacement character', '&#0;', '\uFFFD'],
    ['surrogate code point becomes the replacement character', '&#xD800;', '\uFFFD'],
    ['out-of-range code point becomes the replacement character', '&#x110000;', '\uFFFD'],
    ['nbsp is a non-breaking space that the final trim strips', '&nbsp;', ''],
    ['nbsp stays inside the text', 'a&nbsp;b', 'a\u00A0b'],
    ['semicolon-less entity is not decoded', '&amp', '&amp'],
  ])('%s', (_name, input, expected) => {
    expect(htmlToPlainText(input)).toBe(expected);
  });
});
